import { fetchTranscript, listLanguages, type CaptionTrackInfo, type FetchParams } from "youtube-transcript-plus";
import { decodeHTML } from "entities";
import type { ContentAdapter } from "./types";
import { ADAPTER_MESSAGES } from "../failures";
export function youtubeId(input: string): string | null {
  const u = new URL(input);
  if (
    ![
      "youtube.com",
      "www.youtube.com",
      "m.youtube.com",
      "music.youtube.com",
      "youtu.be",
    ].includes(u.hostname)
  )
    return null;
  const id =
    u.hostname === "youtu.be"
      ? u.pathname.slice(1)
      : u.searchParams.get("v") ||
        u.pathname.match(/^\/(?:shorts|embed|live)\/([^/]+)/)?.[1];
  return id && /^[\w-]{11}$/.test(id) ? id : null;
}

export function selectCaptionTrack(tracks: CaptionTrackInfo[], original: string | null, manual?: string): { track: CaptionTrackInfo | null; reason: "original" | "english-fallback" | "english-original-unknown" | "manual" | "needs-selection" | "unavailable" } {
  if (!tracks.length) return { track: null, reason: "unavailable" };
  const preferred = (language: string) => tracks.filter((t) => t.languageCode.toLowerCase() === language.toLowerCase()).sort((a,b) => Number(a.isAutoGenerated)-Number(b.isAutoGenerated))[0];
  const preferredFamily = (language: string) => tracks.filter((t) => t.languageCode.toLowerCase().split("-")[0] === language.toLowerCase().split("-")[0])
    .sort((a,b) => Number(a.isAutoGenerated)-Number(b.isAutoGenerated) || Number(b.languageCode.toLowerCase() === language.toLowerCase())-Number(a.languageCode.toLowerCase() === language.toLowerCase()))[0];
  if (manual) {
    const track = preferred(manual);
    if (!track) throw new Error(ADAPTER_MESSAGES.trackGone);
    return { track, reason: "manual" };
  }
  if (original) {
    const track = preferredFamily(original);
    if (track) return { track, reason: "original" };
  }
  const english = preferredFamily("en");
  if (english) return { track: english, reason: original ? "english-fallback" : "english-original-unknown" };
  return { track: null, reason: "needs-selection" };
}

async function originalAudioLanguage(videoId: string): Promise<string | null> {
  try {
    const response = await fetch(`https://www.youtube.com/watch?v=${videoId}`, { signal: AbortSignal.timeout(15_000), headers: { "User-Agent": "Mozilla/5.0" } });
    if (!response.ok || Number(response.headers.get("content-length")) > 2_000_000) return null;
    const html = await response.text();
    if (html.length > 2_000_000) return null;
    const tracks = [...html.matchAll(/"audioTrack":(\{[^{}]{1,500}\})/g)]
      .map((match) => { try { return JSON.parse(match[1]!) as { id?: string; isAutoDubbed?: boolean }; } catch { return null; } })
      .filter((track) => track && track.isAutoDubbed !== true && typeof track.id === "string") as { id: string }[];
    const languages = [...new Set(tracks.map((track) => track.id.split(".")[0]!).filter((lang) => /^[a-z]{2,3}(?:-[A-Z]{2})?$/.test(lang)))];
    return languages.length === 1 ? languages[0]! : null;
  } catch { return null; }
}

type CaptionChoice = ReturnType<typeof selectCaptionTrack>;
type LoadedCaption = { text: string; title: string };
export async function resolveCaption(
  tracks: CaptionTrackInfo[], original: string | null, manual: string | undefined,
  load: (track: CaptionTrackInfo) => Promise<LoadedCaption>,
): Promise<{ selected: CaptionChoice; text: string; title: string; issues: string[] }> {
  let selected = selectCaptionTrack(tracks, original, manual);
  const issues: string[] = [];
  let text = "";
  let title = "YouTube video";
  if (selected.track) {
    try {
      const loaded = await load(selected.track);
      if (!loaded.text.trim()) throw new Error(ADAPTER_MESSAGES.transcriptEmpty);
      text = loaded.text;
      title = loaded.title || title;
    } catch (error) {
      const firstError = error instanceof Error ? error.message : "Transcript fetch failed";
      const englishTracks = tracks.filter((track) => track !== selected.track && /^en(?:-|$)/i.test(track.languageCode));
      const fallback = selected.reason === "original" && englishTracks.length
        ? selectCaptionTrack(englishTracks, original) : null;
      if (fallback?.track) {
        try {
          const loaded = await load(fallback.track);
          if (!loaded.text.trim()) throw new Error(ADAPTER_MESSAGES.englishTranscriptEmpty);
          text = loaded.text;
          title = loaded.title || title;
          selected = fallback;
          if (fallback.reason !== "original") issues.push(`Original-language captions could not be loaded: ${firstError}`);
        } catch (secondError) {
          issues.push(firstError, secondError instanceof Error ? secondError.message : "English transcript fetch failed");
        }
      } else issues.push(firstError);
    }
  } else if (selected.reason === "needs-selection") issues.push("Choose an available subtitle track to extract a transcript.");
  else issues.push("No public transcript is available; paste subtitles manually.");
  if (text && selected.reason === "english-fallback") issues.push("Original-language captions were unavailable; English was used instead.");
  if (text && selected.reason === "english-original-unknown") issues.push("Original audio language could not be verified; English was used.");
  return { selected, text, title, issues };
}

async function fetchChosenTranscript(videoId: string, chosen: CaptionTrackInfo): Promise<LoadedCaption> {
  const transcript = await fetchTranscript(videoId, {
    lang: chosen.languageCode, videoDetails: true, retries: 0, signal: AbortSignal.timeout(45_000),
    playerFetch: async (params: FetchParams) => {
      const response = await fetch(params.url, { method: params.method, body: params.body, headers: params.headers, signal: params.signal });
      if (!response.ok) return response;
      const data = await response.json() as { captions?: { playerCaptionsTracklistRenderer?: { captionTracks?: { languageCode: string; kind?: string }[] } } };
      const list = data.captions?.playerCaptionsTracklistRenderer?.captionTracks;
      const score = (track: { languageCode: string; kind?: string }) =>
        Number(track.languageCode !== chosen.languageCode) * 2 + Number((track.kind === "asr") !== chosen.isAutoGenerated);
      if (list) list.sort((a,b) => score(a) - score(b));
      return Response.json(data);
    },
  });
  return { title: transcript.videoDetails.title || "YouTube video", text: transcript.segments.map((s) => `[${Math.floor(s.offset / 60)}:${String(Math.floor(s.offset % 60)).padStart(2, "0")}] ${decodeHTML(s.text)}`).join("\n\n") };
}

export const youtubeAdapter: ContentAdapter = {
  name: "youtube",
  matches: (url) => !!youtubeId(url),
  async discover(_env, url, _job, manual) {
    const videoId = youtubeId(url)!;
    let tracks: CaptionTrackInfo[] = [];
    let trackError: string | null = null;
    try { tracks = await listLanguages(videoId, { retries: 0, signal: AbortSignal.timeout(30_000) }); }
    catch (error) { trackError = error instanceof Error ? error.message : "Caption listing failed"; }
    const original = await originalAudioLanguage(videoId);
    const result = await resolveCaption(tracks, original, manual, (chosen) => fetchChosenTranscript(videoId, chosen));
    const { text, title, issues, selected } = result;
    if (!text && trackError) issues.unshift(trackError);
    return {
      source: "youtube", title, text, media: [],
      details: { type: "youtube-video", completeness: text && !issues.length ? "verified" : "unverified", issues,
        transcript: { tracks, originalLanguage: original, selectedLanguage: text ? selected.track?.languageCode || null : null, reason: selected.reason } },
    };
  },
};
