export type Tag = {
  id: string;
  name: string;
  description: string;
  threshold: number;
  version: number;
  origin?: "manual" | "auto";
};
export type Evaluation = {
  tag_id: string;
  probability: number;
  threshold: number;
  tag_version: number;
  description: string;
  content_version: number;
  model: string;
  evaluated_at: string;
  batch_id: string;
  chunks: number;
};
export type Question = {
  type: "noul" | "choice" | "score";
  instructions: string;
  criteria: Record<string, string> | string[];
};
export type Answer =
  | { type: "noul"; noul: number }
  | {
      type: "choice";
      choice: string;
      probabilities: Record<string, number>;
      confidence: number;
    }
  | {
      type: "score";
      score: number;
      confidence: number;
      probabilities: Record<string, number>;
      legend: Record<string, string>;
    }
  | { type: "multi"; probabilities: Record<string, number> }; // key → p(yes)
export type LensType = "noul" | "choice" | "multi" | "score";
export type LensOption = { key: string; label: string; description: string };
export type LensLevel = { label: string; description: string };
export type Lens = {
  id: string;
  name: string;
  type: LensType;
  question: string;
  options: LensOption[]; // choice + multi (choice includes auto "other")
  levels: LensLevel[]; // score, low → high, 2–10
  criteria: { yes: string; no: string }; // noul only
  threshold: number;
  version: number;
  created_at: string;
};
export type LensResult = {
  lens_id: string;
  answer: Answer;
  lens_version: number;
  content_version: number;
  model: string;
  evaluated_at: string;
  batch_id: string;
};
export type Link = {
  id: string;
  original_url: string;
  url: string;
  domain: string;
  title: string;
  description: string;
  image: string | null;
  favicon: string | null;
  status: "pending" | "ready" | "failed";
  created_at: string;
  tags: Tag[];
  evaluations: Evaluation[];
  content_key: string | null;
  content_version: number;
  content_source: string | null;
  content_state: "missing" | "queued" | "ready" | "partial" | "failed";
  content_error: string | null;
  content_updated_at: string | null;
  content_details: string | null;
  media?: MediaItem[];
  lens_results: LensResult[];
};
export type MediaItem = {
  media_key: string;
  position: number;
  kind: "image" | "video";
  url: string;
  preview_url: string | null;
  ocr_state: "pending" | "done" | "no_text" | "failed" | "skipped";
  ocr_text: string | null;
  ocr_error: string | null;
  ocr_model: string | null;
};
export type ContentDetails = {
  type: "youtube-video" | "youtube-post" | "instagram-post" | "instagram-reel" | "x-post" | "web";
  completeness: "verified" | "unverified";
  issues: string[];
  transcript?: {
    tracks: { languageCode: string; languageName: string; isAutoGenerated: boolean }[];
    originalLanguage: string | null;
    selectedLanguage: string | null;
    reason: "original" | "english-fallback" | "english-original-unknown" | "manual" | "needs-selection" | "unavailable";
  };
};
export type Job = {
  id: string;
  batch_id: string;
  link_id: string;
  title: string;
  status: "queued" | "running" | "done" | "failed";
  step: string;
  error: string | null;
  result: string | null;
  usage?: JobUsage | null;
};
export type JobUsage = {
  input_tokens: number;
  output_tokens: number;
  browser_ms: number;
  duration_ms: number;
  model: string | null;
  usd: number | null;
  unknown_cost_calls: number;
};
export type BatchUsage = {
  input_tokens: number;
  output_tokens: number;
  browser_ms: number;
  model: string | null;
  usd: number | null;
  unknown_cost_calls: number;
};
export type Batch = {
  id: string;
  kind: "extract" | "autotag" | "lens" | "query";
  config: string;
  created_at: string;
  total: number;
  done: number;
  failed: number;
  active: number;
  usage?: BatchUsage | null;
};
export type Capabilities = {
  markdown: boolean;
  jev: boolean;
  provider: string;
};
export type Library = {
  links: Link[];
  tags: Tag[];
  lenses: Lens[];
  batches: Batch[];
  capabilities: Capabilities;
};
export type UsageEvent = {
  id: string;
  batch_id: string | null;
  link_id: string | null;
  title: string | null;
  provider: string;
  service: string;
  model: string | null;
  operation: string;
  status: string;
  input_tokens: number | null;
  output_tokens: number | null;
  browser_ms: number | null;
  estimated_usd: number | null;
  usd?: number | null;
  created_at: string;
  error: string | null;
};
export type UsageTotals = {
  usd: number | null;
  input_tokens: number;
  output_tokens: number;
  browser_ms: number;
  calls: number;
  unknown_cost_calls: number;
};
