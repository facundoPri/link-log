import type { ContentDetails } from "../types";

type CaptionTrack = NonNullable<ContentDetails["transcript"]>["tracks"][number];
export function captionMenuTracks(tracks: CaptionTrack[]): CaptionTrack[] {
  const byLanguage = new Map<string, CaptionTrack>();
  for (const track of tracks) {
    const key = track.languageCode.toLowerCase();
    const previous = byLanguage.get(key);
    if (!previous || (previous.isAutoGenerated && !track.isAutoGenerated)) byLanguage.set(key, track);
  }
  return [...byLanguage.values()];
}

export function youtubeId(url: string): string | null {
  try {
    const u = new URL(url);
    const host = u.hostname.replace(/^www\./, "");
    if (host === "youtu.be") {
      const id = u.pathname.slice(1).split("/")[0];
      return id || null;
    }
    if (host === "youtube.com" || host === "music.youtube.com") {
      if (u.pathname === "/watch") return u.searchParams.get("v");
      const shorts = u.pathname.match(/^\/shorts\/([^/?]+)/);
      if (shorts) return shorts[1]!;
    }
    if (host === "m.youtube.com" && u.pathname === "/watch")
      return u.searchParams.get("v");
    return null;
  } catch {
    return null;
  }
}
